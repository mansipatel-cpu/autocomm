export class VoiceLibraryService {
  static getVoices(filters = {}) {
    let voices = [...PRESET_VOICES];

    if (filters.gender && filters.gender !== 'all') {
      voices = voices.filter((v) => v.gender.toLowerCase() === filters.gender.toLowerCase());
    }

    if (filters.accent && filters.accent !== 'all') {
      voices = voices.filter((v) => v.accent.toLowerCase().includes(filters.accent.toLowerCase()));
    }

    if (filters.search) {
      const q = filters.search.toLowerCase();
      voices = voices.filter(
        (v) =>
          v.name.toLowerCase().includes(q) ||
          v.tone.toLowerCase().includes(q) ||
          v.category.toLowerCase().includes(q) ||
          v.accent.toLowerCase().includes(q)
      );
    }

    return voices;
  }

  static getVoiceById(voiceId) {
    return PRESET_VOICES.find((v) => v.id === voiceId) || PRESET_VOICES[0];
  }
}
